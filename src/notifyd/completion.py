"""`notifyd completion zsh|bash|fish`: completion scripts generated from the argparse tree.

Arguments may carry `.complete`: 'files', 'presets' (live, from `notifyd presets --names`) or
'commands' (notifyd's own commands); choices complete as themselves.
"""

import argparse
from dataclasses import dataclass, field


@dataclass
class Option:
    flags: list
    help: str
    takes_value: bool
    repeat: bool
    choices: list | None
    complete: str | None
    metavar: str


@dataclass
class Positional:
    name: str
    help: str
    optional: bool
    many: bool
    choices: list | None
    complete: str | None


@dataclass
class Command:
    path: list
    help: str = ''
    options: list = field(default_factory=list)
    positionals: list = field(default_factory=list)
    commands: dict = field(default_factory=dict)


def walk(parser, path=('notifyd',), help_text=''):
    node = Command(path=list(path), help=help_text)
    for action in parser._actions:
        if action.help == argparse.SUPPRESS:
            continue
        if isinstance(action, argparse._SubParsersAction):
            helps = {choice.dest: choice.help for choice in action._choices_actions}
            for name, sub in action.choices.items():
                node.commands[name] = walk(sub, (*path, name), helps.get(name) or '')
            continue
        choices = [str(c) for c in action.choices] if action.choices else None
        complete = getattr(action, 'complete', None)
        if action.option_strings:
            node.options.append(Option(
                flags=list(action.option_strings), help=action.help or '', takes_value=action.nargs != 0,
                repeat=isinstance(action, argparse._AppendAction), choices=choices, complete=complete,
                metavar=str(action.metavar or action.dest).lower()))
        else:
            node.positionals.append(Positional(
                name=str(action.metavar or action.dest).lower(), help=action.help or '',
                optional=action.nargs in ('?', '*'), many=action.nargs in ('*', '+'), choices=choices,
                complete=complete))
    return node


def all_nodes(node):
    yield node
    for child in node.commands.values():
        yield from all_nodes(child)


def script(shell, parser):
    root = walk(parser)
    return {'bash': bash, 'zsh': zsh, 'fish': fish}[shell](root)


# -- bash ------------------------------------------------------------------------

def _bash_quote(text):
    return "'" + text.replace("'", "'\\''") + "'"


def bash(root):
    cmds, opts, valued, optcomp, poscomp = [], [], [], [], []
    for node in all_nodes(root):
        key = ' '.join(node.path)
        if node.commands:
            cmds.append(f'  [{_bash_quote(key)}]={_bash_quote(" ".join(node.commands))}')
        opts.append(f'  [{_bash_quote(key)}]={_bash_quote(" ".join(f for o in node.options for f in o.flags))}')
        valued.append(f'  [{_bash_quote(key)}]='
                      f'{_bash_quote(" ".join(f for o in node.options if o.takes_value for f in o.flags))}')
        for option in node.options:
            what = _bash_what(option.choices, option.complete)
            if option.takes_value and what:
                for flag in option.flags:
                    optcomp.append(f'  [{_bash_quote(key + " " + flag)}]={_bash_quote(what)}')
        for index, positional in enumerate(node.positionals):
            what = _bash_what(positional.choices, positional.complete)
            if what:
                poscomp.append(f'  [{_bash_quote(f"{key} {index}")}]={_bash_quote(what)}')
                if positional.many:
                    for later in range(index + 1, index + 8):
                        poscomp.append(f'  [{_bash_quote(f"{key} {later}")}]={_bash_quote(what)}')
    tables = (
        'declare -gA _notifyd_cmds=(\n' + '\n'.join(cmds) + '\n)\n'
        'declare -gA _notifyd_opts=(\n' + '\n'.join(opts) + '\n)\n'
        'declare -gA _notifyd_valued=(\n' + '\n'.join(valued) + '\n)\n'
        'declare -gA _notifyd_optcomp=(\n' + '\n'.join(optcomp) + '\n)\n'
        'declare -gA _notifyd_poscomp=(\n' + '\n'.join(poscomp) + '\n)\n'
    )
    return f'''# bash completion for notifyd (generated by `notifyd completion bash`)
{tables}
_notifyd_values() {{
  local what=$1 cur=$2
  case $what in
    files) compopt -o filenames 2>/dev/null; COMPREPLY=($(compgen -f -- "$cur")) ;;
    presets) COMPREPLY=($(compgen -W "$(notifyd presets --names 2>/dev/null)" -- "$cur")) ;;
    commands) COMPREPLY=($(compgen -W "${{_notifyd_cmds[notifyd]}}" -- "$cur")) ;;
    choices:*) COMPREPLY=($(compgen -W "${{what#choices:}}" -- "$cur")) ;;
  esac
}}

_notifyd() {{
  local cur=${{COMP_WORDS[COMP_CWORD]}} prev=${{COMP_WORDS[COMP_CWORD-1]}}
  local path=notifyd word i skip=0 npos=0
  COMPREPLY=()
  for ((i = 1; i < COMP_CWORD; i++)); do
    word=${{COMP_WORDS[i]}}
    if ((skip)); then skip=0; continue; fi
    if [[ $word == -* ]]; then
      [[ " ${{_notifyd_valued[$path]}} " == *" $word "* ]] && skip=1
      continue
    fi
    if [[ -n ${{_notifyd_cmds[$path]}} && " ${{_notifyd_cmds[$path]}} " == *" $word "* ]]; then
      path="$path $word"; npos=0
    else
      ((npos++))
    fi
  done
  if [[ " ${{_notifyd_valued[$path]}} " == *" $prev "* ]]; then
    _notifyd_values "${{_notifyd_optcomp[$path $prev]}}" "$cur"
    return
  fi
  if [[ $cur == -* ]]; then
    COMPREPLY=($(compgen -W "${{_notifyd_opts[$path]}}" -- "$cur"))
  elif [[ -n ${{_notifyd_cmds[$path]}} ]]; then
    COMPREPLY=($(compgen -W "${{_notifyd_cmds[$path]}}" -- "$cur"))
  else
    _notifyd_values "${{_notifyd_poscomp[$path $npos]}}" "$cur"
  fi
}}
complete -F _notifyd notifyd
'''


def _bash_what(choices, complete):
    if complete:
        return complete
    if choices:
        return 'choices:' + ' '.join(choices)
    return ''


# -- zsh -------------------------------------------------------------------------

def _zsh_help(text):
    return (text.replace('\\', '\\\\').replace('[', '\\[').replace(']', '\\]').replace("'", "'\\''")
            .replace('\n', ' '))


def _zsh_message(text):
    return text.replace(':', '\\:').replace("'", "'\\''")


def _zsh_action(choices, complete):
    if complete == 'files':
        return '_files'
    if complete == 'presets':
        return '_notifyd_presets'
    if complete == 'commands':
        return '_notifyd_cmd_notifyd_commands'
    if choices:
        return '(' + ' '.join(choices) + ')'
    return ' '


def _zsh_function(node):
    return '_notifyd_cmd_' + '_'.join(part.replace('-', '_') for part in node.path)


def _zsh_option(option):
    help_text = _zsh_help(option.help)
    value = ''
    if option.takes_value:
        value = f':{_zsh_message(option.metavar)}:{_zsh_action(option.choices, option.complete)}'
    star = '*' if option.repeat else ''
    if len(option.flags) == 1:
        return f"'{star}{option.flags[0]}[{help_text}]{value}'"
    exclusive = '' if option.repeat else '(' + ' '.join(option.flags) + ')'
    return f"'{exclusive}{star}'{{{','.join(option.flags)}}}'[{help_text}]{value}'"


def zsh(root):
    functions = []
    for node in all_nodes(root):
        name = _zsh_function(node)
        specs = [_zsh_option(option) for option in node.options]
        if node.commands:
            listing = '\n'.join(f"    '{cmd}:{_zsh_help(child.help).replace(':', chr(92) + ':')}'"
                                for cmd, child in node.commands.items())
            functions.append(f'{name}_commands() {{\n  local -a commands=(\n{listing}\n  )\n'
                             f"  _describe -t commands 'notifyd command' commands\n}}\n")
            cases = '\n'.join(f'        {cmd}) {_zsh_function(child)} ;;' for cmd, child in node.commands.items())
            specs += [f"': :{name}_commands'", "'*:: :->args'"]
            body = ('  local curcontext="$curcontext" state line\n  typeset -A opt_args\n'
                    '  _arguments -C \\\n    ' + ' \\\n    '.join(specs) + ' && return\n'
                    f'  case $state in\n    args)\n      case $words[1] in\n{cases}\n      esac ;;\n  esac\n')
        else:
            for positional in node.positionals:
                colons = '*:' if positional.many else ('::' if positional.optional else ':')
                specs.append(f"'{colons}{_zsh_message(positional.name)}:"
                             f"{_zsh_action(positional.choices, positional.complete)}'")
            body = '  _arguments \\\n    ' + ' \\\n    '.join(specs) + '\n' if specs else '  _message "no arguments"\n'
        functions.append(f'{name}() {{\n{body}}}\n')
    return ('#compdef notifyd\n# zsh completion for notifyd (generated by `notifyd completion zsh`)\n\n'
            '_notifyd_presets() {\n  local -a presets=(${(f)"$(notifyd presets --names 2>/dev/null)"})\n'
            "  _describe -t presets 'preset' presets\n}\n\n"
            + '\n'.join(functions) +
            '\n_notifyd() {\n  _notifyd_cmd_notifyd "$@"\n}\n\n'
            'if [[ $zsh_eval_context[-1] == loadautofunc ]]; then\n  _notifyd "$@"\nelse\n'
            '  compdef _notifyd notifyd\nfi\n')


# -- fish ------------------------------------------------------------------------

def _fish_quote(text):
    return "'" + text.replace('\\', '\\\\').replace("'", "\\'") + "'"


def _fish_values(choices, complete):
    if complete == 'files':
        return '-r -F'
    if complete == 'presets':
        return "-x -a '(notifyd presets --names 2>/dev/null)'"
    if complete == 'commands':
        return None
    if choices:
        return '-x -a ' + _fish_quote(' '.join(choices))
    return '-x'


def fish(root):
    paths = [' '.join(node.path) for node in all_nodes(root)]
    lines = [
        '# fish completion for notifyd (generated by `notifyd completion fish`)',
        'complete -c notifyd -f',
        'set -g __notifyd_paths ' + ' '.join(_fish_quote(p) for p in paths),
        'function __notifyd_path',
        '    set -l path notifyd',
        '    for token in (commandline -opc)[2..-1]',
        "        string match -q -- '-*' $token; and continue",
        '        contains -- "$path $token" $__notifyd_paths; and set path "$path $token"',
        '    end',
        '    echo $path',
        'end',
        'function __notifyd_is',
        '    test (__notifyd_path) = "$argv[1]"',
        'end',
    ]
    for node in all_nodes(root):
        condition = "-n " + _fish_quote('__notifyd_is "' + ' '.join(node.path) + '"')
        for cmd, child in node.commands.items():
            lines.append(f'complete -c notifyd {condition} -a {cmd} -d {_fish_quote(child.help)}')
        for option in node.options:
            parts = []
            for flag in option.flags:
                if flag.startswith('--'):
                    parts.append(f'-l {flag[2:]}')
                elif len(flag) == 2:
                    parts.append(f'-s {flag[1]}')
                else:
                    parts.append(f'-o {flag[1:]}')
            values = _fish_values(option.choices, option.complete) if option.takes_value else ''
            lines.append(f'complete -c notifyd {condition} {" ".join(parts)} {values} '
                         f'-d {_fish_quote(option.help)}'.replace('  ', ' '))
        for positional in node.positionals:
            if positional.complete == 'commands':
                for cmd, child in root.commands.items():
                    lines.append(f'complete -c notifyd {condition} -a {cmd} -d {_fish_quote(child.help)}')
                continue
            values = _fish_values(positional.choices, positional.complete)
            if values and values != '-x':
                lines.append(f'complete -c notifyd {condition} {values} -d {_fish_quote(positional.help)}')
    return '\n'.join(lines) + '\n'
